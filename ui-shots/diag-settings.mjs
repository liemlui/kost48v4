import { chromium } from 'playwright';
const API = 'http://localhost:3000/api';
const APP = 'http://localhost:5173';
const res = await fetch(`${API}/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ identifier: 'owner@kost48.com', password: 'Owner#2026' }) });
const token = (await res.json())?.data?.accessToken;
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript((t) => window.localStorage.setItem('kost48_access_token', t), token);
const p = await ctx.newPage();
const errs = [];
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
p.on('pageerror', (e) => errs.push('PAGEERROR: ' + (e.message || e)));
await p.goto(APP + '/settings?tab=tarif', { waitUntil: 'networkidle', timeout: 30000 }).catch((e) => errs.push('GOTO: ' + e.message));
await p.waitForTimeout(1500);
const txt = (await p.locator('body').innerText().catch(() => '')).slice(0, 300);
console.log('BODY TEXT (300):', JSON.stringify(txt));
console.log('ERRORS:', errs.length ? errs.slice(0, 6) : 'none');
await p.screenshot({ path: 'ui-shots/diag_settings.png', fullPage: true });
await b.close();
