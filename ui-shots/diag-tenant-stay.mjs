import { chromium } from 'playwright';
const API = 'http://localhost:3000/api';
const APP = 'http://localhost:5173';
const r = await fetch(`${API}/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ identifier: 'maya.tenant@kost48.test', password: 'Tenant#2026' }) });
const token = (await r.json())?.data?.accessToken;
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1100, height: 1000 } });
await ctx.addInitScript((t) => window.localStorage.setItem('kost48_access_token', t), token);
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push('PAGEERROR ' + (e.message || e)));
await p.goto(APP + '/portal/stay', { waitUntil: 'networkidle', timeout: 30000 }).catch((e) => errs.push('GOTO ' + e.message));
await p.waitForTimeout(1500);
await p.screenshot({ path: 'ui-shots/tenant_stay_meter.png', fullPage: true });
const hasBtn = await p.getByRole('button', { name: /Catat Meter/i }).count();
console.log('Catat Meter button count:', hasBtn, '| errors:', errs.length ? errs.slice(0, 4) : 'none');
await b.close();
